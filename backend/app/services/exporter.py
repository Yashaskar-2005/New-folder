def generate_powerpoint_presentation(presentation_data: Dict[str, Any]) -> io.BytesIO:
    """
    Builds a real PowerPoint (.pptx) file using python-pptx from structured presentation slides.
    """
    try:
        from pptx import Presentation
        from pptx.util import Inches, Pt
        from pptx.dml.color import RGBColor
        from pptx.enum.text import PP_ALIGN
        
        prs = Presentation()
        # Set 16:9 slide width/height
        prs.slide_width = Inches(13.333)
        prs.slide_height = Inches(7.5)
        
        slides_list = presentation_data.get("slides", [])
        
        # Color palette
        INDIGO = RGBColor(79, 70, 229)
        DARK_SLATE = RGBColor(15, 23, 42)
        MUTED_GRAY = RGBColor(100, 116, 139)
        WHITE = RGBColor(255, 255, 255)
        
        blank_slide_layout = prs.slide_layouts[6]
        
        for slide_info in slides_list:
            slide = prs.slides.add_slide(blank_slide_layout)
            
            # Slide Title
            title_box = slide.shapes.add_textbox(Inches(1.0), Inches(0.8), Inches(11.333), Inches(1.2))
            tf = title_box.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            p.text = slide_info.get("title", "Slide Title")
            p.font.size = Pt(36)
            p.font.bold = True
            p.font.color.rgb = INDIGO
            
            # Bullets
            content_box = slide.shapes.add_textbox(Inches(1.0), Inches(2.2), Inches(11.333), Inches(3.8))
            ctf = content_box.text_frame
            ctf.word_wrap = True
            
            bullets = slide_info.get("bullets", [])
            for i, bullet_text in enumerate(bullets):
                bp = ctf.paragraphs[0] if i == 0 else ctf.add_paragraph()
                bp.text = f"•  {bullet_text}"
                bp.font.size = Pt(22)
                bp.font.color.rgb = DARK_SLATE
                bp.space_after = Pt(14)
            
            # Speaker notes & visual cue footer
            notes = slide_info.get("speaker_notes", "")
            if notes:
                footer_box = slide.shapes.add_textbox(Inches(1.0), Inches(6.2), Inches(11.333), Inches(0.8))
                ftf = footer_box.text_frame
                ftf.word_wrap = True
                fp = ftf.paragraphs[0]
                fp.text = f"Presenter Note: {notes}"
                fp.font.size = Pt(13)
                fp.font.italic = True
                fp.font.color.rgb = MUTED_GRAY
                
        output_stream = io.BytesIO()
        prs.save(output_stream)
        output_stream.seek(0)
        return output_stream
    except Exception as e:
        print(f"[PPTX Generation Error]: {e}")
        return io.BytesIO()
