def generate_markdown_export(job_title: str, outputs: List[Dict[str, Any]]) -> str:
    """Generates a master Markdown report containing all generated transformations."""
    md = f"# Transformation Report: {job_title}\n"
    md += f"*Generated by Gen AI Content Repurposing Platform*\n\n"
    md += f"---\n\n"
    
    for item in outputs:
        fmt = item.get("output_type", "Output").upper()
        title = item.get("title", fmt)
        content = item.get("content_markdown", "")
        md += f"## [{fmt}] {title}\n\n"
        md += f"{content}\n\n"
        md += f"---\n\n"
        
    return md

